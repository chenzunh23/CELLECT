def main() -> None:
    args = build_arg_parser().parse_args()
    args.root = _expand(args.root)
    args.checkpoint = _expand(args.checkpoint)
    args.out_dir = _expand(args.out_dir)
    args.reference_dir = _expand(args.reference_dir) if args.reference_dir else None
    args.cutout_dir = _expand(args.cutout_dir) if args.cutout_dir else None
    args.band_reference_root = _expand(args.band_reference_root) if args.band_reference_root else None
    args.targets_dir = _expand(args.targets_dir) if args.targets_dir else args.root / "targets"
    args.image_cache_dir = _expand(args.image_cache_dir) if args.image_cache_dir else None
    args.lsst_aggregate_csv = _expand(args.lsst_aggregate_csv) if args.lsst_aggregate_csv else None
    args.out_dir.mkdir(parents=True, exist_ok=True)

    per_cutout_rows, summary = evaluate_astro(args)
    astro_aggregate = aggregate_rows(per_cutout_rows)
    combined = list(astro_aggregate)
    if not args.no_lsst_overlay and args.lsst_aggregate_csv is not None and args.lsst_aggregate_csv.exists():
        combined.extend(
            load_lsst_aggregate(
                args.lsst_aggregate_csv,
                label=args.lsst_label,
                mag_min=args.mag_min,
                mag_max=args.mag_max,
            )
        )

    write_csv(args.out_dir / "astro_magnitude_completeness_per_cutout.csv", per_cutout_rows)
    write_csv(args.out_dir / "astro_magnitude_completeness_aggregate.csv", astro_aggregate)
    write_csv(args.out_dir / "magnitude_completeness_comparison.csv", combined)
    plot_completeness(
        args.out_dir / "magnitude_completeness_comparison.png",
        combined,
        title=f"Completeness by reference magnitude ({args.mag_min:g}-{args.mag_max:g})",
    )
    plot_count_bars(
        args.out_dir / "magnitude_counts_gt_detected.png",
        combined,
        title=f"GT and detected sources by magnitude ({args.mag_min:g}-{args.mag_max:g})",
    )
    completeness_focus = filter_rows_by_mag(
        combined,
        mag_min=args.completeness_plot_min,
        mag_max=args.mag_max,
    )
    plot_completeness(
        args.out_dir / "magnitude_completeness_23_30.png",
        completeness_focus,
        title=f"Completeness by reference magnitude ({args.completeness_plot_min:g}-{args.mag_max:g})",
    )
    metadata = {
        "args": {key: str(value) if isinstance(value, Path) else value for key, value in vars(args).items()},
        "astro_summary": summary,
        "lsst_aggregate_csv_used": str(args.lsst_aggregate_csv)
        if not args.no_lsst_overlay and args.lsst_aggregate_csv and args.lsst_aggregate_csv.exists()
        else None,
    }
    (args.out_dir / "magnitude_completeness_metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))
    print(f"wrote {args.out_dir / 'magnitude_completeness_comparison.png'}")
    print(f"wrote {args.out_dir / 'magnitude_counts_gt_detected.png'}")
    print(f"wrote {args.out_dir / 'magnitude_completeness_23_30.png'}")
    print(f"wrote {args.out_dir / 'magnitude_completeness_comparison.csv'}")


if __name__ == "__main__":
    main()
